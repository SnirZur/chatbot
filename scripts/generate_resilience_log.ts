{
   const tempDir = mkdtempSync(path.join(os.tmpdir(), 'chatbot-idempotency-'));
   try {
      const store = createIdempotencyStore(tempDir);
      const invocationId = 'duplicate-local-demo';
      const firstSeen = await store
         .get(invocationId)
         .then(() => true)
         .catch(() => false);
      if (!firstSeen) {
         await markProcessed(store, invocationId);
         log(`first delivery -> processed invocationId=${invocationId}`);
      }
      const duplicateSeen = await store
         .get(invocationId)
         .then(() => true)
         .catch(() => false);
      log(
         duplicateSeen
            ? `duplicate delivery -> ignored invocationId=${invocationId}`
            : `duplicate delivery -> ERROR invocationId=${invocationId}`
      );
      log(
         'result: only one ToolInvocationResulted would be emitted for the duplicate key'
      );
      await store.close();
   } finally {
      rmSync(tempDir, { recursive: true, force: true });
   }
}

