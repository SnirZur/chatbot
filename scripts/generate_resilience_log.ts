type PlanStep = {
   id: string;
   purpose: string;
   dependsOn: string[];
   tool: string;
   parameters: Record<string, unknown>;
};

type PlanState = {
   conversationId: string;
   userId: string;
   plan: PlanStep[];
   final_answer_synthesis_required: boolean;
   stepIndex: number;
   results: Array<{ tool: string; result: unknown }>;
   planCompletedEmitted: boolean;
   status: 'RUNNING' | 'COMPLETED' | 'FAILED';
};

type ConversationEvent = {
   conversationId: string;
   userId: string;
   timestamp: string;
   eventType: string;
   payload: Record<string, unknown>;
};

const lines: string[] = [];

const log = (line: string) => {
   lines.push(line);
};

const resolvePlaceholders = (
   params: Record<string, unknown>,
   results: PlanState['results']
) => {
   const replace = (value: unknown): unknown => {
      if (typeof value === 'string') {
         return value.replace(/<result_from_tool_(\d+)>/g, (_match, index) => {
            const result = results[Number(index) - 1];
            if (!result) return '';
            const output = result.result as
               | { data?: unknown; text?: unknown; rate?: unknown }
               | string
               | Record<string, unknown>;
            if (typeof output === 'string') return output;
            if (output && typeof output === 'object' && 'data' in output) {
               return String(output.data ?? '');
            }
            if (output && typeof output === 'object' && 'rate' in output) {
               return String(output.rate ?? '');
            }
            if (output && typeof output === 'object' && 'text' in output) {
               return String(output.text ?? '');
            }
            return JSON.stringify(output ?? {});
         });
      }
      if (Array.isArray(value)) return value.map(replace);
      if (value && typeof value === 'object') {
         return Object.fromEntries(
            Object.entries(value).map(([key, nested]) => [key, replace(nested)])
         );
      }
      return value;
   };

   return replace(params) as Record<string, unknown>;
};

const applyEvent = (
   state: Map<string, PlanState>,
   event: ConversationEvent
) => {
   if (event.eventType === 'PlanGenerated') {
      state.set(event.conversationId, {
         conversationId: event.conversationId,
         userId: event.userId,
         plan: (event.payload.plan ?? []) as PlanStep[],
         final_answer_synthesis_required: Boolean(
            event.payload.final_answer_synthesis_required
         ),
         stepIndex: 0,
         results: [],
         planCompletedEmitted: false,
         status: 'RUNNING',
      });
      return;
   }

   const current = state.get(event.conversationId);
   if (!current) return;

   if (event.eventType === 'ToolInvocationResulted') {
      const stepIndex = Number(event.payload.stepIndex);
      if (!current.results[stepIndex]) {
         current.results[stepIndex] = {
            tool: String(event.payload.tool ?? ''),
            result: event.payload.result,
         };
      }
      current.stepIndex = Math.max(current.stepIndex, stepIndex + 1);
      if (current.stepIndex >= current.plan.length)
         current.status = 'COMPLETED';
      return;
   }

   if (event.eventType === 'PlanCompleted') {
      current.planCompletedEmitted = true;
      current.status = 'COMPLETED';
   }
};

const nextTransition = (state: PlanState) => {
   if (!state.planCompletedEmitted && state.stepIndex >= state.plan.length) {
      return {
         kind: 'PlanCompleted',
         payload: {
            final_answer_synthesis_required:
               state.final_answer_synthesis_required,
         },
      };
   }
   if (state.status === 'RUNNING' && state.stepIndex < state.plan.length) {
      const step = state.plan[state.stepIndex];
      return {
         kind: 'ToolInvocationRequested',
         payload: {
            invocationId: `${state.conversationId}-${state.stepIndex}`,
            tool: step.tool,
            stepIndex: state.stepIndex,
            parameters: resolvePlaceholders(step.parameters, state.results),
         },
      };
   }
   return null;
};

